#!/usr/bin/env python3
"""ZINZIN: the engine's sine table (4096 points + 2 guard points), const so it stays in flash.

    python3 tools/make_tables.py            -> zinzin/gen/zz_tables.h
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "zinzin", "gen", "zz_tables.h")
N = 4096
vals = ["%.9ff" % math.sin(2 * math.pi * i / N) for i in range(N + 2)]
open(OUT, "w").write("/* generated by tools/make_tables.py: do not edit */\n#pragma once\n#define ZZ_SIN_N %d\n"
                     "static const float ZZ_SIN[%d] = {%s};\n" % (N, N + 2, ", ".join(vals)))
print("zz_tables.h written")
