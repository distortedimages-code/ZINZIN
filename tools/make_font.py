#!/usr/bin/env python3
"""ZINZIN: the pixel fonts as C bitmaps (Latin-1, accents included), all crisp at their design size.

    ZZ_FONT_S  Press Start 2P, 8 px        (the marquee, counters, labels, the big ZINZIN)
    ZZ_FONT_T  Terminus 12 (6 x 12)        (window titles and messages)
    ZZ_FONT_B  Terminus 16 bold (8 x 16)   (big readouts)

Press Start 2P and Terminus are SIL OFL 1.1 (assets/fonts/LICENSE-*.txt). Each glyph is one uint16 per row, bit 15
the leftmost pixel, with its advance.

    python3 tools/make_font.py              -> zinzin/gen/zz_font.h
"""
import io
import os
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "assets", "fonts")
OUT = os.path.join(ROOT, "zinzin", "gen", "zz_font.h")
CODES = list(range(32, 127)) + list(range(160, 256))


def from_ttf(woff, size, height, base):
    f = TTFont(os.path.join(FONTS, woff))
    f.flavor = None
    b = io.BytesIO()
    f.save(b)
    font = ImageFont.truetype(io.BytesIO(b.getvalue()), size)
    rows, adv = [], []
    for cp in CODES:
        ch = chr(cp)
        w = max(1, min(16, int(round(font.getlength(ch)))))
        im = Image.new("L", (24, height + 8), 0)
        ImageDraw.Draw(im).text((0, base), ch, font=font, fill=255, anchor="ls")
        adv.append(w)
        for y in range(height):
            bits = 0
            for x in range(min(16, w)):
                if im.getpixel((x, y)) >= 128:
                    bits |= 1 << (15 - x)
            rows.append(bits)
    return rows, adv


def from_bdf(name):
    """a BDF font: each glyph placed in the font's box (ascent above the baseline)"""
    lines = open(os.path.join(FONTS, name), encoding="latin-1").read().split("\n")
    ascent = descent = 0
    glyphs = {}
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("FONT_ASCENT"):
            ascent = int(ln.split()[1])
        elif ln.startswith("FONT_DESCENT"):
            descent = int(ln.split()[1])
        elif ln.startswith("STARTCHAR"):
            enc = dw = None
            bbx = None
            bm = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                p = lines[i].split()
                if p[0] == "ENCODING":
                    enc = int(p[1])
                elif p[0] == "DWIDTH":
                    dw = int(p[1])
                elif p[0] == "BBX":
                    bbx = [int(v) for v in p[1:5]]
                elif p[0] == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        bm.append(int(lines[i], 16))
                        i += 1
                    break
                i += 1
            glyphs[enc] = (dw, bbx, bm)
        i += 1
    height = ascent + descent
    rows, adv = [], []
    for cp in CODES:
        g = glyphs.get(cp) or glyphs.get(ord("?"))
        dw, (bw, bh, bx, by), bm = g
        nbytes = (bw + 7) // 8
        out = [0] * height
        top = ascent - (by + bh)              # the glyph's first row in the box
        for r, v in enumerate(bm):
            y = top + r
            if 0 <= y < height:
                bits = v << (16 - nbytes * 8) if nbytes <= 2 else v >> (nbytes * 8 - 16)
                out[y] = (bits >> bx) & 0xFFFF if bx >= 0 else (bits << -bx) & 0xFFFF
        rows += out
        adv.append(dw)
    return rows, adv, height


def emit(name, rows, adv, height, out):
    out.append("static const uint16_t ZZ_FROWS_%s[%d] = {%s};" % (name, len(rows), ", ".join("0x%04X" % r for r in rows)))
    out.append("static const uint8_t ZZ_FADV_%s[%d] = {%s};" % (name, len(adv), ", ".join(str(a) for a in adv)))
    out.append("static const zz_font_t ZZ_FONT_%s = {%d, ZZ_FROWS_%s, ZZ_FADV_%s};" % (name, height, name, name))


def main():
    out = ["/* generated by tools/make_font.py from Press Start 2P and Terminus (SIL OFL 1.1): do not edit */",
           "#pragma once", "#include <stdint.h>",
           "typedef struct { uint8_t h; const uint16_t *rows; const uint8_t *adv; } zz_font_t;",
           "/* glyph index: codes 32..126 then 160..255 */",
           "static inline int zz_glyph(uint32_t cp) { return cp >= 32u && cp < 127u ? (int)cp - 32 : (cp >= 160u && cp < 256u ? (int)cp - 160 + 95 : -1); }"]
    rows, adv = from_ttf("press-start-2p-latin-400-normal.woff", 8, 8, 8)
    emit("S", rows, adv, 8, out)
    rows, adv, h = from_bdf("ter-u12n.bdf")
    emit("T", rows, adv, h, out)
    rows, adv, h = from_bdf("ter-u16b.bdf")
    emit("B", rows, adv, h, out)
    open(OUT, "w").write("\n".join(out) + "\n")
    print("zz_font.h written")


if __name__ == "__main__":
    main()
